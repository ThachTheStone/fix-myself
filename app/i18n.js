const DICTIONARIES = { en, vi };
let current = 'en';

export function detectLanguage(storage, navigatorLanguages = []) {
  const saved = storage?.getItem(LANGUAGE_KEY);
  if (saved in DICTIONARIES) return saved;
  return navigatorLanguages.some((tag) => String(tag).toLowerCase().startsWith('vi')) ? 'vi' : 'en';
}

export function setLanguage(language) {
  current = language in DICTIONARIES ? language : 'en';
  return current;
}

export const getLanguage = () => current;

// Locale for dates and times. English keeps the system's English variant
// (for example en-GB date order); Vietnamese always uses vi-VN.
export function locale(navigatorLanguage = globalThis.navigator?.language) {
  if (current === 'vi') return 'vi-VN';
  return String(navigatorLanguage ?? '').toLowerCase().startsWith('en') ? navigatorLanguage : 'en';
}

// t('key', { n: 2 }) picks 'key.one' or 'key.other' when the key has plural forms.
export function t(key, params = {}) {
  const dictionary = DICTIONARIES[current];
  let resolved = key;
  if (typeof params.n === 'number' && !(key in en)) resolved = key + (params.n === 1 ? '.one' : '.other');
  const template = dictionary[resolved] ?? en[resolved] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

export function translateError(message) {
  if (current === 'en' || !message) return message;
  if (message in ERRORS_VI) return ERRORS_VI[message];
  const tooLong = /^(.+) must be (\d+) characters or fewer\.$/.exec(message);
  if (tooLong && FIELD_KEYS[tooLong[1]]) {
    return t('error.tooLong', { label: t(FIELD_KEYS[tooLong[1]]), max: tooLong[2] });
  }
  return message;
}

// Fills elements marked with data-i18n (text), data-i18n-placeholder and
// data-i18n-aria-label from the current dictionary.
export function translateDocument(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll('[data-i18n-placeholder]')) node.placeholder = t(node.dataset.i18nPlaceholder);
  for (const node of root.querySelectorAll('[data-i18n-aria-label]')) node.setAttribute('aria-label', t(node.dataset.i18nAriaLabel));
  root.documentElement.lang = current;
}

